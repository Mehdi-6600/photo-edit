export const dictionaries: Record<Lang, Dict> = { en: en as Dict, fa };

export function translate(lang: Lang, key: DictKey, vars?: Record<string, string | number>): string {
  let text: string = dictionaries[lang][key] ?? en[key];
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.split(`{${name}}`).join(String(value));
    }
  }
  return text;
}

export function makeTranslator(lang: Lang) {
  return (key: DictKey, vars?: Record<string, string | number>) => translate(lang, key, vars);
}

export type Translator = ReturnType<typeof makeTranslator>;
